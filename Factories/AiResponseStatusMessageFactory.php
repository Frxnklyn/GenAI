<?php
namespace axenox\GenAI\Factories;

use axenox\GenAI\AI\ResponseStatusMessages\AiResponseStatusMessage;
use axenox\GenAI\AI\ResponseStatusMessages\AiResponseStatusMessageWithAction;
use axenox\GenAI\Interfaces\AiResponseStatusMessageInterface;
use axenox\GenAI\Widgets\AIChat;
use exface\Core\CommonLogic\UxonObject;
use exface\Core\Exceptions\InvalidArgumentException;
use exface\Core\Factories\AbstractStaticFactory;
use exface\Core\Factories\ActionFactory;
use exface\Core\Interfaces\Actions\ActionInterface;
use exface\Core\Interfaces\DataSheets\DataSheetInterface;
use exface\Core\Interfaces\WidgetInterface;

